"""Load the synthetic demonstration dataset into the database.

Run with: python -m app.scripts.seed_synthetic

This replaces any existing synthetic records rather than merging into them.
The generator is deterministic, so a re-run reproduces the same dataset; and a
partial mix of an older and a newer synthetic vintage would silently corrupt
the persistence analysis, which reads the whole synthetic set as one study
population. Records with source != 'synthetic' are never touched.
"""
from datetime import datetime
from pathlib import Path

import pandas as pd
from geoalchemy2.shape import from_shape
from shapely.geometry import Point

from app.core.config import get_settings
from app.db.session import SessionLocal
from app.models.dataset import Dataset
from app.models.incident import Incident
from app.models.municipality import Municipality
from app.models.persistence import PersistenceRecord
from app.services.persistence_service import recompute_persistence

CSV_PATH = Path(__file__).resolve().parents[3] / "data" / "synthetic" / "synthetic_incidents.csv"

DATASET_NAME = "PPALMA Synthetic Demonstration Dataset"


def _optional(row, column: str):
    value = row.get(column)
    if value is None or (isinstance(value, float) and value != value):
        return None
    return value


def run() -> None:
    df = pd.read_csv(CSV_PATH)
    db = SessionLocal()
    try:
        municipalities = {m.name: m.id for m in db.query(Municipality).all()}
        missing = sorted(set(df["municipality"]) - set(municipalities))
        if missing:
            raise SystemExit(
                f"Municipalities not seeded: {missing}. "
                f"Run `python -m app.scripts.seed_municipalities` first."
            )

        dates = pd.to_datetime(df["incident_date"])
        dataset = db.query(Dataset).filter(Dataset.name == DATASET_NAME).first()
        if dataset is None:
            dataset = Dataset(name=DATASET_NAME)
            db.add(dataset)
        dataset.description = (
            "Reproducible fictional dataset generated by app.services.synthetic_data "
            "(fixed seed). Structure mirrors the expected anonymized PNP incident export. "
            "Must never be presented as official PNP data."
        )
        dataset.source = "synthetic"
        dataset.version = "2.0"
        dataset.is_active = True
        dataset.record_count = len(df)
        dataset.period_start = dates.min().to_pydatetime()
        dataset.period_end = dates.max().to_pydatetime()
        db.flush()

        removed = db.query(Incident).filter(Incident.source == "synthetic").delete()
        db.flush()

        for _, row in df.iterrows():
            point = Point(float(row["longitude"]), float(row["latitude"]))
            incident_time = None
            raw_time = _optional(row, "incident_time")
            if isinstance(raw_time, str) and raw_time:
                incident_time = datetime.strptime(raw_time, "%H:%M").time()

            db.add(
                Incident(
                    incident_id=row["incident_id"],
                    crime_type=row["crime_type"],
                    incident_date=datetime.strptime(row["incident_date"], "%Y-%m-%d").date(),
                    incident_time=incident_time,
                    municipality_id=municipalities[row["municipality"]],
                    municipality=row["municipality"],
                    barangay=row["barangay"],
                    general_location=_optional(row, "general_location"),
                    latitude=float(row["latitude"]),
                    longitude=float(row["longitude"]),
                    geom=from_shape(point, srid=4326),
                    crime_classification=_optional(row, "crime_classification"),
                    index_nonindex_flag=_optional(row, "index_nonindex_flag"),
                    coordinate_source=_optional(row, "coordinate_source"),
                    coordinate_precision=_optional(row, "coordinate_precision"),
                    case_status_generalized=_optional(row, "case_status_generalized"),
                    dataset_id=dataset.id,
                    source="synthetic",
                )
            )

        db.commit()
        print(f"Replaced {removed} previous synthetic incidents with {len(df)}.")
        print(f"  dataset: {DATASET_NAME} (id={dataset.id}, v{dataset.version})")
        print(f"  period:  {dates.min().date()} to {dates.max().date()}")

        settings = get_settings()
        db.query(PersistenceRecord).delete()
        records = recompute_persistence(
            db,
            eps_km=settings.dbscan_eps_km,
            min_samples=settings.dbscan_min_samples,
            match_distance_km=settings.persistence_match_distance_km,
            score_threshold=settings.persistence_score_threshold,
        )
        db.add_all(records)
        db.commit()
        print(f"Computed {len(records)} initial persistence records.")
    finally:
        db.close()


if __name__ == "__main__":
    run()
